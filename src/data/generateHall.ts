const createSeatsFromRows = (
  section: string,
  sectionId: string,
  rows: RowDefinition[],
): Seat[] =>
  rows.flatMap((rowDefinition) =>
    rowDefinition.xs.map((x, index) => ({
      id: `${sectionId}-r${rowDefinition.row}-s${index + 1}`,
      section,
      row: rowDefinition.row,
      seat: index + 1,
      x,
      y: rowDefinition.y,
      tariffId: NO_TARIFF_ID,
    })),
  );

const createParterSeats = (): Seat[] =>
  parterRows.flatMap((rowDefinition) => {
    const leftSeats = rowDefinition.left.map((x, index) => ({
      id: `parter-left-r${rowDefinition.row}-s${index + 1}`,
      section: "Партер",
      row: rowDefinition.row,
      seat: index + 1,
      x,
      y: rowDefinition.y,
      tariffId: NO_TARIFF_ID,
    }));

    const rightSeats = rowDefinition.right.map((x, index) => ({
      id: `parter-right-r${rowDefinition.row}-s${leftSeats.length + index + 1}`,
      section: "Партер",
      row: rowDefinition.row,
      seat: leftSeats.length + index + 1,
      x,
      y: rowDefinition.y,
      tariffId: NO_TARIFF_ID,
    }));

    return [...leftSeats, ...rightSeats];
  });

export const generateHallSeats = (): Seat[] => [
  ...createSeatsFromRows("Бельэтаж", "beletage", beletageRows),
  ...createSeatsFromRows("Ложа", "lodge", lodgeRows),
  ...createSeatsFromRows(
    "Бельэтаж правая сторона",
    "beletage-right-side",
    sideBeletageRows,
  ),
  ...createParterSeats(),
];
